function build(brand: Brand, rows: Row[]): Paint[] {
  const prefix = brand.toLowerCase().replace(/\s+/g, '-');
  const seen = new Set<string>();
  return rows.map(([name, type, hex]) => {
    // Some names exist in two ranges (e.g. Hoeth Blue as Layer and Dry).
    let id = `${prefix}:${name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`;
    if (seen.has(id)) id += `-${type}`;
    seen.add(id);
    return { id, name, brand, type, hex };
  });
}

